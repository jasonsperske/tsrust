const escapeHtml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Highlight Rust with TSRust's own lexer. */
function highlightRust(text: string): string {
  const toks = lex(text, 0, new Diagnostics());
  let html = "";
  let pos = 0;
  const gap = (to: number) => {
    html += escapeHtml(text.slice(pos, to)).replace(/(\/\/[^\n]*)/g, '<span class="tok-comment">$1</span>');
    pos = to;
  };
  toks.forEach((t, i) => {
    if (t.kind === "eof") return;
    gap(t.span.start);
    const next = toks[i + 1];
    let cls = "";
    if (t.kind === "keyword") cls = t.value === "true" || t.value === "false" ? "tok-lit" : "tok-kw";
    else if (t.kind === "int" || t.kind === "float") cls = "tok-num";
    else if (t.kind === "string" || t.kind === "char") cls = "tok-str";
    else if (t.kind === "lifetime") cls = "tok-life";
    else if (t.kind === "ident") {
      if (next?.kind === "punct" && next.value === "!") cls = "tok-macro";
      else if (/^[A-Z]/.test(String(t.value)) || /^(i|u|f)\d+$|^(bool|char|str|usize|isize)$/.test(String(t.value))) cls = "tok-type";
      else if (next?.kind === "punct" && next.value === "(") cls = "tok-fn";
    }
    const body = escapeHtml(text.slice(t.span.start, t.span.end));
    html += cls ? `<span class="${cls}">${body}</span>` : body;
    pos = t.span.end;
  });
  gap(text.length);
  return html;
}

function slug(text: string): string {
  return text.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function rewriteHref(href: string): string {
  if (/^[a-z]+:/i.test(href) || href.startsWith("#")) return href;
  const [path, hash] = href.split("#");
  if (/^[\w-]+\.md$/.test(path)) return (path === "index.md" ? "index.html" : path.replace(/\.md$/, ".html")) + (hash ? `#${hash}` : "");
  if (path.startsWith("../")) {
    const target = path.slice(3);
    if (target.startsWith("playground")) return `playground/`;
    if (repo) return `${repo}/blob/main/${target}${hash ? `#${hash}` : ""}`;
  }
  return href;
}

const marked = new Marked({
  gfm: true,
  walkTokens(token) {
    if (token.type === "link") (token as Tokens.Link).href = rewriteHref((token as Tokens.Link).href);
  },
  renderer: {
    code({ text, lang }) {
      if (lang === "mermaid") return `<pre class="mermaid">${escapeHtml(text)}</pre>\n`;
      const body = lang === "rust" || lang === "rs" ? highlightRust(text) : escapeHtml(text);
      return `<pre><code class="language-${escapeHtml(lang ?? "text")}">${body}</code></pre>\n`;
    },
    heading({ tokens, depth }) {
      const inner = this.parser.parseInline(tokens);
      return `<h${depth} id="${slug(inner)}">${inner}</h${depth}>\n`;
    },
  },
});

interface Page {
  file: string;
  out: string;
  title: string;
  html: string;
}

function layout(page: Page, pages: Page[], body: string): string {
  const idx = pages.indexOf(page);
  const prev = pages[idx - 1], next = pages[idx + 1];
  const nav = pages.map((p) => `<li><a href="${p.out}"${p === page ? ' aria-current="page"' : ""}>${escapeHtml(p.title)}</a></li>`).join("\n");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(page.title)} · TSRust</title>
<meta name="description" content="TSRust: a Rust compiler written in TypeScript, built to teach how Rust works." />
<link rel="stylesheet" href="style.css" />
</head>
<body>
<header class="topbar">
  <a class="brand" href="index.html"><span class="logo">TS<b>Rust</b></span><span class="tagline">two can play at this game: a port of Rust to TypeScript</span></a>
  <nav><a href="index.html"${page.out === "index.html" ? ' aria-current="page"' : ""}>Docs</a><a href="playground/">Playground</a>${repo ? `<a href="${repo}">GitHub</a>` : ""}</nav>
</header>
<div class="docs">
  <aside class="sidebar"><ol>${nav}</ol><a class="cta" href="playground/">Open the playground</a></aside>
  <article>
${body}
<nav class="pager">${prev ? `<a href="${prev.out}">← ${escapeHtml(prev.title)}</a>` : "<span></span>"}${next ? `<a href="${next.out}">${escapeHtml(next.title)} →</a>` : "<span></span>"}</nav>
  </article>
</div>
<script type="module">
import mermaid from "${MERMAID}";
const dark = matchMedia("(prefers-color-scheme: dark)").matches;
mermaid.initialize({ startOnLoad: true, theme: dark ? "dark" : "neutral", securityLevel: "strict", flowchart: { htmlLabels: true } });
</script>
</body>
</html>
`;
}

function buildDocs(): number {
  const docsDir = join(root, "docs");
  const files = readdirSync(docsDir).filter((f) => f.endsWith(".md")).sort((a, b) => (a === "index.md" ? -1 : b === "index.md" ? 1 : a.localeCompare(b)));
  const pages: Page[] = files.map((file) => {
    const md = readFileSync(join(docsDir, file), "utf8");
    const title = (/^#\s+(.+)$/m.exec(md)?.[1] ?? file).replace(/`/g, "");
    return { file, out: file === "index.md" ? "index.html" : file.replace(/\.md$/, ".html"), title: file === "index.md" ? "Overview" : title, html: marked.parse(md) as string };
  });
  for (const page of pages) {
    let body = page.html;
    if (page.out === "index.html") {
      body = body.replace(/(<\/h1>)/, `$1\n<div class="hero"><p><b>Two can play at this game:</b> a Rust compiler written in TypeScript, built so you can read every stage, from tokens to borrow checking to bytecode, and run it in your browser.</p><a class="button" href="playground/">Try the playground</a><a class="button secondary" href="01-lexing.html">Start reading</a></div>`);
    }
    writeFileSync(join(out, page.out), layout(page, pages, body));
  }
  return pages.length;
}

// ---------------------------------------------------------------------------
// 3. Playground bundle
// ---------------------------------------------------------------------------

async function buildPlayground() {
  mkdirSync(join(out, "playground"), { recursive: true });
  await build({
    entryPoints: [join(root, "playground/main.ts")],
    bundle: true,
    format: "esm",
    target: "es2022",
    minify: true,
    sourcemap: true,
    outfile: join(out, "playground/playground.js"),
    logLevel: "warning",
  });
  cpSync(join(root, "playground/index.html"), join(out, "playground/index.html"));
  cpSync(join(root, "playground/playground.css"), join(out, "playground/playground.css"));
}

// ---------------------------------------------------------------------------

execFileSync(process.execPath, [join(root, "scripts/gen-std.ts")], { stdio: "inherit" });
if (existsSync(out)) rmSync(out, { recursive: true });
mkdirSync(out, { recursive: true });
cpSync(join(root, "site-src/style.css"), join(out, "style.css"));
writeFileSync(join(out, ".nojekyll"), "");
const nExamples = generateExamples();
await buildPlayground();
const nPages = buildDocs();
console.log(`site/ built: ${nPages} doc pages, playground with ${nExamples} examples${repo ? `, source links → ${repo}` : " (set package.json \"repository\" for source links)"}`);
