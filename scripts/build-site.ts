/**
 * Builds the GitHub Pages site into `site/`:
 *
 *   site/index.html, site/NN-*.html   the docs (from docs/*.md)
 *   site/playground/                   the in-browser compiler
 *   site/style.css                     shared styles
 *
 * Source links like `../src/lexer/lexer.ts` in the docs are rewritten to point
 * at the GitHub repository (from $GITHUB_REPOSITORY in CI, or package.json).
 *
 *   npm run build:site
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { build } from "esbuild";
import { Marked, type Tokens } from "marked";
import { Diagnostics } from "../src/diagnostics.ts";
import { lex } from "../src/lexer/lexer.ts";

const root = join(import.meta.dirname, "..");
const out = join(root, "site");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const repo = process.env.GITHUB_REPOSITORY
  ? `https://github.com/${process.env.GITHUB_REPOSITORY}`
  : typeof pkg.repository === "string" ? pkg.repository.replace(/\.git$/, "") : pkg.repository?.url?.replace(/^git\+/, "").replace(/\.git$/, "");
const MERMAID = "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs";

