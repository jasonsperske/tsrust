function titleFromFile(name: string): string {
  const base = name.replace(/\.rs$/, "");
  const m = /^(E\d{4})_(.*)$/.exec(base);
  if (m) return `${m[1]} · ${m[2].replace(/_/g, " ")}`;
  const n = /^(\d+)_(.*)$/.exec(base);
  const words = (n ? n[2] : base).replace(/^panic_/, "").replace(/_/g, " ");
  const title = words.charAt(0).toUpperCase() + words.slice(1);
  return n ? `${n[1]} · ${title}` : title;
}

function generateExamples() {
  const ex = join(root, "examples");
  const list: { id: string; title: string; group: string; files: Record<string, string>; entry: string; open: string; name: string }[] = [];
  const single = (dir: string, file: string, group: string) => {
    const name = file.replace(/\.rs$/, "");
    list.push({ id: name, title: titleFromFile(file), group, files: { "/main.rs": readFileSync(join(dir, file), "utf8") }, entry: "/main.rs", open: "/main.rs", name });
  };
  for (const f of readdirSync(ex).filter((f) => f.endsWith(".rs")).sort()) single(ex, f, "A tour of Rust");
  const pkgRoot = join(ex, "packages");
  const files: Record<string, string> = {};
  const walk = (d: string) => {
    for (const n of readdirSync(d).sort()) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else files["/" + relative(pkgRoot, p).split("\\").join("/")] = readFileSync(p, "utf8");
    }
  };
  walk(pkgRoot);
  list.push({ id: "packages", title: "Three crates: app → geometry → util", group: "Packages and modules", files, entry: "/app", open: "/app/src/main.rs", name: "app" });
  const errs = join(ex, "errors");
  for (const f of readdirSync(errs).filter((f) => f.endsWith(".rs") && f.startsWith("E")).sort()) single(errs, f, "Compile errors (on purpose)");
  for (const f of readdirSync(errs).filter((f) => f.startsWith("panic_")).sort()) single(errs, f, "Runtime panics");
  writeFileSync(
    join(root, "playground/examples.generated.ts"),
    `// GENERATED by scripts/build-site.ts from /examples. Do not edit.\nexport interface Example { id: string; title: string; group: string; files: Record<string, string>; entry: string; open: string; name: string }\nexport const EXAMPLES: Example[] = ${JSON.stringify(list, null, 1)};\n`,
  );
  return list.length;
}

